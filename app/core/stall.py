"""Почему клиент замолчал — и стоит ли его вообще дожимать.

Дожим «клиент молчит N часов» одинаково пишет и тому, кто ушёл с возражением,
и тому, кто сказал «жду, оформляйте». Это разные ситуации, и текст должен быть
разный, а иногда писать нельзя вовсе.

Причину не спрашиваем у модели отдельным интентом: классификатор уже разобрал
последнее сообщение клиента, и интент оттуда говорит, С ЧЕМ клиент ушёл. Нам
остаётся сопоставить его с состоянием чата. Это дешевле одного лишнего запроса
к Poe на каждый молчащий чат и, главное, предсказуемо: одна и та же ситуация
всегда даёт один и тот же дожим.
"""

from __future__ import annotations

# Мы должны клиенту, а не он нам: ждёт расчёт, фото или живого человека.
# Дожимать здесь — хамство: клиент ждёт ответа, которого мы не дали.
WAITING_US = "waiting_us"
# Явный отказ. Молчим совсем.
REFUSED = "refused"
# Ушёл с сомнением: дорого, подумаю, посоветуюсь.
OBJECTION = "objection"
# Отложенный спрос с названным сроком: ремонт, переезд, сдача квартиры.
DEFERRED = "deferred"
# Сказал «беру» / оставил контакт и пропал в шаге от сделки.
READY_STALLED = "ready_stalled"
# Просто исчез посреди разговора без сигнала.
GHOSTED = "ghosted"

_BY_INTENT: dict[str, str] = {
    "refusal": REFUSED,
    "objection": OBJECTION,
    "discount_request": OBJECTION,
    "deferred_demand": DEFERRED,
    "ready_to_order": READY_STALLED,
    "contact_shared": READY_STALLED,
    # Эти три означают, что мяч на нашей стороне
    "human_request": WAITING_US,
    "staff_action": WAITING_US,
    "warranty": WAITING_US,
}

# Для каждой причины: сколько часов молчания ждать перед ступенью и что писать.
# Порядок = ступени. Пустой кортеж — не дожимаем никогда.
_PLAN: dict[str, tuple[tuple[float, str], ...]] = {
    WAITING_US: (),
    REFUSED: (),
    # Клиент сам попросил время подумать. Дёргать его через четыре часа — значит
    # не услышать то, что он только что сказал. Ждём сутки, потом ещё раз
    # через четверо, и отступаем.
    OBJECTION: (
        (
            24,
            "Здравствуйте! Вы говорили, что нужно подумать — не тороплю. Если "
            "остались сомнения по цене или материалу, скажите: подберу вариант "
            "под ваш бюджет.",
        ),
        (
            96,
            "Добрый день! Больше не буду напоминать о себе. Решите вернуться к "
            "мебели — просто напишите, всё по вашему запросу у меня сохранено.",
        ),
    ),
    # Названа объективная причина ждать: ремонт, переезд, сдача квартиры
    DEFERRED: (
        (
            72,
            "Здравствуйте! Вы говорили, что мебель понадобится позже — я пометил "
            "себе. Напомнить ближе к сроку или лучше не беспокоить?",
        ),
        (
            24 * 14,
            "Добрый день! Решил уточнить, как продвигается ремонт. Если стены уже "
            "готовы — самое время снять размеры, очередь на замер сейчас небольшая.",
        ),
    ),
    # Сказал «беру» и пропал в шаге от сделки — здесь медлить нельзя
    READY_STALLED: (
        (
            2,
            "Здравствуйте! Вы на связи? Готов закрепить за вами время замера — "
            "подскажите удобный день.",
        ),
        (
            12,
            "Добрый день! Не хочу вас потерять. Если планы изменились — просто "
            "скажите, и я перестану писать. Если нет — назовите удобный день, "
            "и я передам замерщику.",
        ),
    ),
    # Просто откололся посреди разговора, ничего не объяснив
    GHOSTED: (
        (
            4,
            "Здравствуйте! Подскажите, остались ли вопросы по мебели? Могу "
            "сориентировать по материалам, срокам или стоимости.",
        ),
        (
            48,
            "Добрый день! Больше беспокоить не буду. Если мебель ещё актуальна — "
            "напишите, ваши размеры и пожелания у меня сохранены.",
        ),
    ),
}

ALL_REASONS = (WAITING_US, REFUSED, OBJECTION, DEFERRED, READY_STALLED, GHOSTED)


def reason_for(last_intent: str | None, *, has_pending_price: bool = False) -> str:
    """Почему клиент замолчал.

    Незакрытая заявка на расчёт перебивает интент: чем бы разговор ни кончился,
    если владелец ещё не прислал цифры — ждёт нас клиент, а не мы его.
    """
    if has_pending_price:
        return WAITING_US
    return _BY_INTENT.get((last_intent or "").strip().lower(), GHOSTED)


def snoozed_return(reason: str | None = None) -> str:
    """Возврат к клиенту в срок, о котором он сам попросил.

    Здороваемся и прямо ссылаемся на договорённость: человек назвал срок
    неделю назад и, скорее всего, забыл. Напоминание без повода читается
    как рассылка, с поводом — как выполненное обещание.

    Саму причину клиенту не показываем: это заметка для менеджера, и в
    скобках посреди фразы она выглядит как машинный след.
    """
    _ = reason
    return (
        "Здравствуйте! Вы просили вернуться к вопросу по мебели позже — "
        "как и договаривались, напоминаю о себе. Актуально ещё? "
        "Если да, подберу варианты и посчитаю под ваши размеры."
    )


def max_stage(reason: str) -> int:
    return len(_PLAN.get(reason, ()))


def next_followup(
    reason: str,
    *,
    stage: int,
    silent_hours: float,
    base_hours: float | None = None,
) -> str | None:
    """Текст следующего дожима — или None, если писать рано или уже хватит.

    base_hours (FOLLOWUP_SILENCE_HOURS) двигает только первую ступень для
    тех, кто пропал молча. Остальным задержку из .env не навязываем: клиент,
    попросивший время подумать, не должен получать напоминание через четыре
    часа только потому, что кто-то поменял переменную окружения.
    """
    plan = _PLAN.get(reason, ())
    if stage >= len(plan):
        return None
    delay, text = plan[stage]
    if stage == 0 and base_hours is not None and reason == GHOSTED:
        delay = max(0.0, base_hours)
    if silent_hours < delay:
        return None
    return text
