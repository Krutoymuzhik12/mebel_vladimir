def stem(word: str) -> str:
    """Грубая нормализация окончания. Полноценный стеммер здесь избыточен:
    нам нужно лишь свести «диваны», «дивана» и «диваном» к одной форме."""
    low = (word or "").lower()
    for end in _ENDINGS:
        if len(low) - len(end) >= 4 and low.endswith(end):
            return low[: -len(end)]
    return low


def detect_type(title: str, category: str = "") -> str:
    low = f" {(title or '').lower()} "
    for kind, keys in TYPE_RULES:
        if any(k in low for k in keys):
            return kind
    return CATEGORY_TO_TYPE.get((category or "").strip().lower(), "прочее")


def detect_colors(text: str) -> list[str]:
    low = (text or "").lower()
    found: list[str] = []
    for name, pattern in _COLOR_RE:
        if name not in found and pattern.search(low):
            found.append(name)
    return found[:6]


def detect_features(text: str) -> list[str]:
    low = (text or "").lower()
    return [name for name, keys in FEATURES.items() if any(k in low for k in keys)]


def detect_mechanism(text: str) -> str:
    low = (text or "").lower()
    for m in MECHANISMS:
        if m in low:
            return m
    return ""


def type_from_client_words(text: str) -> str:
    """Тип мебели из фразы клиента. Пусто, если он его не назвал."""
    low = f" {(text or '').lower()} "
    for word, kind in CLIENT_SYNONYMS.items():
        if word in low:
            return kind
    guess = detect_type(text)
    return guess if guess != "прочее" else ""
