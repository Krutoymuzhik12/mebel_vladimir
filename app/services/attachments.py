"""Подсказки модели для вложений, которые бот не разбирает по существу.

PDF/DOCX-парсинг был и работал (pypdf/python-docx), но снят по решению
заказчика: документы теперь целиком уходят владельцу через MAX
(app/jobs/document_relay.py), реальный разбор — отдельная задача на потом.

Стикеры и видео сюда не попадают вовсе — orchestrator отбрасывает их раньше,
до диалога. Документ (PDF/Word/др.) тоже не доходит до модели: см.
Orchestrator._on_document — он уходит владельцу напрямую, минуя эту подсказку.
Здесь остались только geo и по-настоящему нераспознанные вложения.
"""

from __future__ import annotations

_HINTS = {
    "geo": (
        "Клиент прислал геолокацию. Поблагодари и при необходимости уточни "
        "адрес текстом (город / улица) для замера."
    ),
    "unsupported": (
        "Клиент прислал вложение, которое система не умеет открыть. "
        "Скажи коротко, что не видишь файл, и попроси описать словами или "
        "прислать фото / текст."
    ),
}


def hint_for(kind: str) -> str:
    return _HINTS.get(kind, "")
